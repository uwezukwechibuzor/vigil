#!/usr/bin/env python3
"""
Generate typed tracking clients from tracking-plan.yaml.
Outputs: generated/tracking.ts, generated/tracking.py, generated/tracking.go

Usage:
    python3 analytics/tracking-plan/codegen.py
    python3 analytics/tracking-plan/codegen.py --validate  (CI mode: check no undeclared events)
"""
import argparse
import os
import re
import sys
import textwrap
from pathlib import Path

try:
    import yaml
except ImportError:
    print("PyYAML not installed. Install with: pip3 install pyyaml", file=sys.stderr)
    sys.exit(1)

PLAN_FILE = Path(__file__).parent / "tracking-plan.yaml"
OUT_DIR = Path(__file__).parent / "generated"


def pascal(s: str) -> str:
    return "".join(w.capitalize() for w in s.split("_"))


def camel(s: str) -> str:
    p = pascal(s)
    return p[0].lower() + p[1:]


def load_plan() -> dict:
    with open(PLAN_FILE) as f:
        return yaml.safe_load(f)


# ── TypeScript ──────────────────────────────────────────────────────────────

TS_TYPE_MAP = {
    "string": "string",
    "integer": "number",
    "float": "number",
    "double": "number",
    "boolean": "boolean",
    "array": "string[]",
}


def ts_prop_type(prop: dict) -> str:
    if "enum" in prop:
        return " | ".join(f'"{v}"' for v in prop["enum"])
    if prop.get("type") == "array":
        item_type = TS_TYPE_MAP.get(prop.get("items", {}).get("type", "string"), "string")
        return f"{item_type}[]"
    return TS_TYPE_MAP.get(prop.get("type", "string"), "string")


def gen_ts(plan: dict) -> str:
    lines = [
        "// AUTO-GENERATED by analytics/tracking-plan/codegen.py — do not edit manually",
        "// Re-generate: python3 analytics/tracking-plan/codegen.py",
        "",
        'import { telemetry } from "./telemetry.js";',
        "",
        "/** Standard properties included on every event. */",
        "export interface StandardProperties {",
        "  event_id?: string;",
        "  occurred_at?: string;",
        "  surface?: 'web' | 'cli' | 'sdk_ts' | 'sdk_py' | 'sdk_go' | 'mcp' | 'backend';",
        "  app_version?: string;",
        "  org_id?: string;",
        "  project_id?: string;",
        "  plan?: 'free' | 'pro' | 'team' | 'enterprise';",
        "  environment?: 'production' | 'staging' | 'development';",
        "  anonymous_id?: string;",
        "  user_id?: string;",
        "  session_id?: string;",
        "  framework?: 'langchain' | 'elizaos' | 'crewai' | 'vercel_ai' | 'none';",
        "  chain_id?: string;",
        "}",
        "",
    ]

    for event in plan["events"]:
        name = event["name"]
        iface = pascal(name) + "Props"
        props = event.get("properties", {})
        required = props.get("required", {})
        optional = props.get("optional", {})

        lines.append(f"/** {event['description']} */")
        lines.append(f"export interface {iface} extends StandardProperties {{")
        for pname, pdef in required.items():
            ts_t = ts_prop_type(pdef)
            lines.append(f"  {pname}: {ts_t};")
        for pname, pdef in optional.items():
            ts_t = ts_prop_type(pdef)
            lines.append(f"  {pname}?: {ts_t};")
        lines.append("}")
        lines.append("")

        fn = "track" + pascal(name)
        lines.append(f"export function {fn}(props: {iface}): void {{")
        lines.append(f'  telemetry.track("{name}", props as Record<string, unknown>);')
        lines.append("}")
        lines.append("")

    # Export all event names as a const tuple for CI validation
    event_names = [f'  "{e["name"]}"' for e in plan["events"]]
    lines.append("/** All registered event names — used by CI to validate no undeclared events. */")
    lines.append("export const REGISTERED_EVENTS = [")
    lines.extend(e + "," for e in event_names)
    lines.append("] as const;")
    lines.append("")
    lines.append("export type EventName = (typeof REGISTERED_EVENTS)[number];")
    lines.append("")

    return "\n".join(lines)


# ── Python ──────────────────────────────────────────────────────────────────

PY_TYPE_MAP = {
    "string": "str",
    "integer": "int",
    "float": "float",
    "double": "float",
    "boolean": "bool",
    "array": "list[str]",
}


def py_prop_type(prop: dict) -> str:
    if "enum" in prop:
        vals = ", ".join(f'"{v}"' for v in prop["enum"])
        return f"Literal[{vals}]"
    if prop.get("type") == "array":
        item_type = PY_TYPE_MAP.get(prop.get("items", {}).get("type", "string"), "str")
        return f"list[{item_type}]"
    return PY_TYPE_MAP.get(prop.get("type", "string"), "str")


def gen_py(plan: dict) -> str:
    lines = [
        "# AUTO-GENERATED by analytics/tracking-plan/codegen.py — do not edit manually",
        "# Re-generate: python3 analytics/tracking-plan/codegen.py",
        "from __future__ import annotations",
        "",
        "from dataclasses import asdict, dataclass, field",
        "from typing import Literal, Optional",
        "",
        "from vigil.telemetry import telemetry as _tel",
        "",
        "REGISTERED_EVENTS: tuple[str, ...] = (",
    ]
    for event in plan["events"]:
        lines.append(f'    "{event["name"]}",')
    lines.append(")")
    lines.append("")

    for event in plan["events"]:
        name = event["name"]
        cls = pascal(name) + "Props"
        props = event.get("properties", {})
        required = props.get("required", {})
        optional = props.get("optional", {})

        lines.append("")
        lines.append(f'@dataclass')
        lines.append(f"class {cls}:")
        lines.append(f'    """{event["description"]}"""')
        # required fields first (no default)
        for pname, pdef in required.items():
            py_t = py_prop_type(pdef)
            lines.append(f"    {pname}: {py_t}")
        # optional fields with None default
        for pname, pdef in optional.items():
            py_t = py_prop_type(pdef)
            lines.append(f"    {pname}: Optional[{py_t}] = None")
        lines.append("")

        fn = "track_" + name
        lines.append(f"def {fn}(props: {cls}) -> None:")
        lines.append(f'    """Fire the {name!r} event."""')
        lines.append(f'    _tel.track("{name}", asdict(props))')
        lines.append("")

    return "\n".join(lines)


# ── Go ──────────────────────────────────────────────────────────────────────

GO_TYPE_MAP = {
    "string": "string",
    "integer": "int64",
    "float": "float64",
    "double": "float64",
    "boolean": "bool",
    "array": "[]string",
}


def go_prop_type(prop: dict) -> str:
    if "enum" in prop:
        return "string"
    if prop.get("type") == "array":
        return "[]string"
    return GO_TYPE_MAP.get(prop.get("type", "string"), "string")


def go_field(pname: str, pdef: dict, optional: bool) -> str:
    t = go_prop_type(pdef)
    tag = f'`json:"{pname},omitempty"`' if optional else f'`json:"{pname}"`'
    return f"\t{pascal(pname)} {t} {tag}"


def gen_go(plan: dict) -> str:
    lines = [
        "// Code generated by analytics/tracking-plan/codegen.py — do not edit manually.",
        "// Re-generate: python3 analytics/tracking-plan/codegen.py",
        "",
        "package tracking",
        "",
        "import (",
        "\t\"github.com/uwezukwechibuzor/vigil/analytics/tracking-plan/generated/internal/tel\"",
        ")",
        "",
        "// RegisteredEvents is the exhaustive list of valid event names.",
        "// CI validates that no code fires events outside this list.",
        "var RegisteredEvents = []string{",
    ]
    for event in plan["events"]:
        lines.append(f'\t"{event["name"]}",')
    lines.append("}")
    lines.append("")

    for event in plan["events"]:
        name = event["name"]
        props_name = pascal(name) + "Props"
        fn_name = "Track" + pascal(name)
        props = event.get("properties", {})
        required = props.get("required", {})
        optional = props.get("optional", {})

        lines.append(f"// {props_name} holds properties for the {name!r} event.")
        lines.append(f"// {event['description']}")
        lines.append(f"type {props_name} struct {{")
        for pname, pdef in required.items():
            lines.append(go_field(pname, pdef, False))
        for pname, pdef in optional.items():
            lines.append(go_field(pname, pdef, True))
        lines.append("}")
        lines.append("")

        lines.append(f"// {fn_name} fires the {name!r} event.")
        lines.append(f"func {fn_name}(props {props_name}) {{")
        lines.append(f'\ttel.Track("{name}", props)')
        lines.append("}")
        lines.append("")

    return "\n".join(lines)


# ── CI validator ─────────────────────────────────────────────────────────────

def validate_events(plan: dict, root: Path) -> int:
    """Scan source files for .track("event") calls and check against plan."""
    registered = {e["name"] for e in plan["events"]}
    errors = 0
    # patterns: telemetry.track("event", ...) / .track("event"
    pattern = re.compile(r'\.track\(\s*["\']([a-z_]+)["\']')
    skip_dirs = {".git", "node_modules", "__pycache__", "target", "dist", "generated"}
    for path in root.rglob("*"):
        if any(p in path.parts for p in skip_dirs):
            continue
        if path.suffix not in {".ts", ".py", ".go"}:
            continue
        if path.name.startswith("tracking."):
            continue
        try:
            text = path.read_text(errors="replace")
        except (OSError, PermissionError):
            continue
        for match in pattern.finditer(text):
            ev = match.group(1)
            if ev not in registered:
                print(f"UNDECLARED EVENT: {ev!r} in {path.relative_to(root)}")
                errors += 1
    if errors == 0:
        print("✓ All tracked events are declared in the tracking plan.")
    return errors


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--validate", action="store_true",
                        help="CI mode: scan for undeclared events, exit 1 if found")
    args = parser.parse_args()

    plan = load_plan()

    if args.validate:
        repo_root = PLAN_FILE.parent.parent.parent
        sys.exit(validate_events(plan, repo_root))

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    ts = gen_ts(plan)
    (OUT_DIR / "tracking.ts").write_text(ts)
    print("✓ Written tracking.ts")

    py = gen_py(plan)
    (OUT_DIR / "tracking.py").write_text(py)
    print("✓ Written tracking.py")

    go_code = gen_go(plan)
    (OUT_DIR / "tracking.go").write_text(go_code)
    print("✓ Written tracking.go")


if __name__ == "__main__":
    main()
